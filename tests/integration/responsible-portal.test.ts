test("reposição: abrir horário, solicitar, decidir e cancelar com tenancy",async()=>{
  const a=await createAccess({customerName:"A",customerEmail:null,plan:"individual",studentLimit:10,code:null});
  const b=await createAccess({customerName:"B",customerEmail:null,plan:"individual",studentLimit:10,code:null});
  ids.push(a.id,b.id);
  const s=await saveStudent(a.id,student());
  const access=await createResponsibleAccess(a.id,s.id,{name:"Mãe",phone:"",email:null,code:null});
  const slot=await createMakeupSlot(a.id,{date:"2030-01-10",startTime:"15:00",endTime:"16:00"});
  await assert.rejects(()=>requestMakeupSlot(b.id,access.id,s.id,slot.id),/não encontrado/);
  await requestMakeupSlot(a.id,access.id,s.id,slot.id);
  let [req]=await database().select().from(makeupRequests).where(eq(makeupRequests.slotId,slot.id));
  let [sl]=await database().select().from(makeupSlots).where(eq(makeupSlots.id,slot.id));
  assert.equal(req.status,"pending");
  assert.equal(sl.status,"requested");
  await assert.rejects(()=>requestMakeupSlot(a.id,access.id,s.id,slot.id),/disponível|pendente/);
  await decideMakeupRequest(a.id,req.id,"approved");
  [sl]=await database().select().from(makeupSlots).where(eq(makeupSlots.id,slot.id));
  [req]=await database().select().from(makeupRequests).where(eq(makeupRequests.id,req.id));
  assert.equal(sl.status,"confirmed");
  assert.equal(req.status,"approved");
  const closed=await createMakeupSlot(a.id,{date:"2030-01-20",startTime:"10:00",endTime:"11:00"});
  await changeMakeupSlotStatus(a.id,closed.id,"unavailable");
  await assert.rejects(()=>requestMakeupSlot(a.id,access.id,s.id,closed.id),/não está mais disponível/);
  const slot3=await createMakeupSlot(a.id,{date:"2030-02-01",startTime:"14:00",endTime:"15:00"});
  await requestMakeupSlot(a.id,access.id,s.id,slot3.id);
  const [req3]=await database().select().from(makeupRequests).where(eq(makeupRequests.slotId,slot3.id));
  await decideMakeupRequest(a.id,req3.id,"rejected");
  [sl]=await database().select().from(makeupSlots).where(eq(makeupSlots.id,slot3.id));
  assert.equal(sl.status,"available");
  const other=await createResponsibleAccess(a.id,s.id,{name:"Avó",phone:"",email:null,code:null});
  await assert.rejects(()=>cancelMakeupRequest(a.id,other.id,req3.id),/não encontrada/);
  await requestMakeupSlot(a.id,access.id,s.id,slot3.id);
  const [req4]=await database().select().from(makeupRequests).where(and(eq(makeupRequests.slotId,slot3.id),eq(makeupRequests.status,"pending")));
  await cancelMakeupRequest(a.id,access.id,req4.id);
  [req]=await database().select().from(makeupRequests).where(eq(makeupRequests.id,req4.id));
  [sl]=await database().select().from(makeupSlots).where(eq(makeupSlots.id,slot3.id));
  assert.equal(req.status,"cancelled");
  assert.equal(sl.status,"available");
  const [sessions]=await database().select().from(responsibleSessions);
  assert.equal(sessions,undefined);
});