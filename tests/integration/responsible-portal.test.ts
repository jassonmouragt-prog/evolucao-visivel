test("portal: criar acesso, listar, bloquear, regenerar e excluir com tenancy",async()=>{
  const a=await createAccess({customerName:"A",customerEmail:null,plan:"individual",studentLimit:10,code:null});
  const b=await createAccess({customerName:"B",customerEmail:null,plan:"individual",studentLimit:10,code:null});
  ids.push(a.id,b.id);
  const s=await saveStudent(a.id,student());
  await assert.rejects(()=>createResponsibleAccess(b.id,s.id,{name:"Mãe",phone:"",email:null,code:null}),/não encontrado/);
  const access=await createResponsibleAccess(a.id,s.id,{name:"Mãe da Maria",phone:"11999999999",email:null,code:null});
  assert.match(access.code,/^[A-Z]{3}-\d[A-Z]\d{2}$/);
  assert.equal((await listResponsibleAccess(b.id,s.id)).length,0);
  assert.equal((await listResponsibleAccess(a.id,s.id)).length,1);
  const manual=await createResponsibleAccess(a.id,s.id,{name:"Pai da Maria",phone:"",email:null,code:"PAPA2026"});
  assert.equal(manual.code,"PAPA2026");
  await assert.rejects(()=>createResponsibleAccess(a.id,s.id,{name:"Pai da Maria",phone:"",email:null,code:"PAPA2026"}),/já existe/);
  await changeResponsibleStatus(a.id,access.id,"blocked");
  const [row]=await database().select().from(responsibleStudentAccess).where(eq(responsibleStudentAccess.id,access.id));
  assert.equal(row.status,"blocked");
  await assert.rejects(()=>changeResponsibleStatus(b.id,access.id,"active"),/não encontrado/);
  const code2=await regenerateResponsibleCode(a.id,access.id);
  assert.notEqual(code2,access.code);
  await deleteResponsibleAccess(a.id,access.id);
  assert.equal((await listResponsibleAccess(a.id,s.id)).length,1);
  await deleteResponsibleAccess(a.id,manual.id);
  const [contact]=await database().select().from(responsibleContacts).where(and(eq(responsibleContacts.accessCodeId,a.id),eq(responsibleContacts.name,"Pai da Maria")));
  assert.equal(contact,undefined);
});
